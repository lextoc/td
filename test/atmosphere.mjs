import assert from 'node:assert/strict';
import { createAtmosphere, extractHighlights } from '../src/atmosphere.js';
const pixels = new Uint8ClampedArray([0,0,0,255, 100,100,100,255, 255,255,255,255, 220,210,190,128]);
extractHighlights(pixels);
assert.equal(pixels[3],0); assert.equal(pixels[7],0); assert.equal(pixels[11],255);
assert.ok(pixels[15] > 0 && pixels[15] < 128);
assert.deepEqual([...pixels.slice(12,15)],[220,210,190], 'Bloom preserves highlight colors');
let depth = 0;
const noop=()=>{}, c = new Proxy({save(){depth++},restore(){depth--}}, {get:(target,key)=>target[key] || noop});
const canvas = {width:390,height:700};
const atmosphere = createAtmosphere(()=>.5);
for(let i=0;i<200;i++) atmosphere.draw(c,canvas,{dt:0,bloom:false});
assert.equal(atmosphere.birdCount,0,'Paused scenes never spawn birds');
for(let i=0;i<110;i++) atmosphere.draw(c,canvas,{dt:.1,bloom:false});
assert.equal(atmosphere.birdCount,4,'A small flock enters after the initial quiet interval');
for(let i=0;i<10000;i++) { atmosphere.draw(c,canvas,{dt:.1,bloom:false}); assert.ok(atmosphere.birdCount<=12,'Flocks stay bounded over long sessions'); }
atmosphere.draw(c,canvas,{dt:.1,bloom:false,reduced:true});
assert.equal(atmosphere.birdCount,0,'Reduced motion removes flyovers');
atmosphere.reset(); assert.equal(atmosphere.birdCount,0);
assert.equal(depth,0,'Canvas state is restored after each pass');
console.log('Atmosphere checks passed: highlight extraction, quiet intervals, paused scenes, bounded flocks, reduced motion and canvas state');
